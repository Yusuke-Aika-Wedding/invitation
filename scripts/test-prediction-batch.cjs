const fs = require('fs'), vm = require('vm'), assert = require('node:assert/strict');
const c = vm.createContext({ Date, Map, console });
vm.runInContext(fs.readFileSync('gas/Code.gs','utf8'),c);
let rows = [], writes = 0, eligible = true;
c.LockService = {getScriptLock:()=>({waitLock(){},releaseLock(){}})};
c.getMainSheet_ = ()=>({});
c.findGuestRecord_ = (_,id)=>id==='Case_ID'?{values:{id,name:'Fixture', reception:eligible?'出席':'欠席',submittedAt:new Date()}}:null;
c.isCompleted_ = ()=>true;
const sheet={getLastRow:()=>rows.length+1,getRange:()=>({setValues(r){writes++; rows.push(...r)},setNumberFormat(){}})};
c.getPredictionSheet_=()=>sheet;
c.readPredictionVotes_=()=>rows.map(r=>({guestId:r[0],questionId:r[2],option:r[3]}));
c.SpreadsheetApp={flush(){}};
const questions=vm.runInContext('PREDICTION_QUESTIONS',c);
const answers=questions.map(q=>({questionId:q.id,option:q.options[0]}));
const call=(a=answers,id='Case_ID')=>c.submitPredictions_({guestId:id,answers:JSON.stringify(a)});
assert.throws(()=>call(answers.slice(0,2)));assert.equal(writes,0);
assert.throws(()=>call([...answers.slice(0,2),{questionId:'Q3',option:'invalid'}]));assert.equal(writes,0);
assert.throws(()=>call([answers[0],answers[0],answers[2]]));assert.equal(writes,0);
assert.throws(()=>call(answers,'case_id'));assert.equal(writes,0);
eligible=false;assert.throws(()=>call());assert.equal(writes,0);eligible=true;
assert.equal(call().ok,true);assert.equal(rows.length,3);assert.equal(writes,1);
assert.equal(call().alreadyVoted,true);assert.equal(rows.length,3);assert.equal(writes,1);
rows=rows.slice(0,1); rows[0][3]=questions[0].options[1];
assert.equal(call().ok,true);assert.equal(rows.length,3);assert.equal(rows[0][3],questions[0].options[1]);
assert.equal(writes,2);
console.log('PASS atomic batch validation, reception gating, case-sensitive IDs, idempotent retries, preserved legacy votes');
